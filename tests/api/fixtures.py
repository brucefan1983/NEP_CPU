"""Small deterministic coverage fixtures, not fitted physical potentials.

Keep the generator and frozen references under review together. No references
are generated by the test runner. Real models are in data/nep and data/qnep.
"""
import math
import random

ALL_FLAGS = (1, 1, 1, 1, 1, 1)
ZBL_COEFFICIENTS = [0.18175, 3.1998, 0.50986, 0.94229, 0.28022, 0.4029, 0.02817, 0.20162]
FLEXIBLE_ZBL = [[0.6, 1.5] + ZBL_COEFFICIENTS,
                [0.8, 2.8] + ZBL_COEFFICIENTS,
                [1.2, 3.4] + ZBL_COEFFICIENTS]


def cluster():
    return dict(type=[0, 1, 0, 1, 0, 1],
                box=[[20.0, 1.3, 0.7], [0.0, 21.0, 0.9], [0.0, 0.0, 22.0]],
                position=[[5., 5., 5.], [6.3, 5.2, 5.4], [5.4, 6.5, 5.9],
                          [7.1, 6.6, 6.2], [6., 7.8, 5.3], [7.7, 5.7, 7.]])


def pair(types, distance):
    frame = cluster()
    frame['type'] = list(types)
    frame['position'] = [[5., 5., 5.], [5. + distance * u for u in (0.36, 0.48, 0.8)]]
    return frame


def small_cell():
    frame = cluster()
    frame['box'] = [[5.8, 0.4, 0.2], [0., 6.1, 0.3], [0., 0., 6.3]]
    frame['position'] = [[x - 4.0 for x in r] for r in frame['position']]
    return frame


def supercell(frame):
    result = dict(type=[], position=[], box=[[3 * x for x in row] for row in frame['box']])
    for a in range(3):
        for b in range(3):
            for c in range(3):
                shift = [sum(row[j] * v for j, v in enumerate((a, b, c))) for row in frame['box']]
                result['type'] += frame['type']
                result['position'] += [[x + y for x, y in zip(r, shift)] for r in frame['position']]
    return result


def model_text(kind='nep', flags=ALL_FLAGS, typewise=False, zbl=None, zero=False, l_max=4):
    dim, neurons, types = 3 + 3 * (l_max + sum(flags)), 8, 2
    ann_count = types * neurons * (dim + 2) + 1
    if kind.startswith('qnep'):
        ann_count += types * neurons + 1
    if 'polarizability' in kind:
        ann_count *= 2
    rng = random.Random(215)
    values = [rng.uniform(-0.3, 0.3) if not zero else 0.0 for _ in range(ann_count + 72)]
    if kind.startswith('qnep'):
        values[ann_count - 2] = 1.7
    fields = [2 * flags[0], *flags[1:]]
    while len(fields) > 2 and fields[-1] == 0:
        fields.pop()
    header = ['nep 2 C Si', 'format_version 1', 'model ' + kind]
    if zbl is not None:
        header += [zbl]
    header += ['cutoff 5 4 4.4 3.6 100 100' if typewise else 'cutoff 5 4 100 100',
               'n_max 2 2', 'basis_size 2 2',
               'l_max ' + str(l_max) + ' ' + ' '.join(map(str, fields)), 'ann 8 0']
    if kind not in ('nep_dipole', 'nep_polarizability'):
        header += ['energy_reference 0 0']
    # Preserve the original fixture's logical coefficients while serializing
    # version-1 [center_type, neighbor_type, n, k] descriptor segments.
    parameters = values[:ann_count]
    for offset in (ann_count, ann_count + 36):
        parameters += [values[offset + nk * 4 + pair] for pair in range(4) for nk in range(9)]
    lines = header + ['@ parameters ' + str(len(parameters))]
    lines += [format(v, '.17g') for v in parameters]
    lines += ['@ q_scaler ' + str(dim)]
    lines += [format(0.7 + 0.03 * d, '.17g') for d in range(dim)]
    if zbl == 'zbl 0 0':
        lines += ['@ zbl_parameters 30']
        lines += [str(v) for row in FLEXIBLE_ZBL for v in row]
    return '\n'.join(lines) + '\n'


def write_models(directory):
    settings = {
        'ordinary': {},
        'typewise': dict(typewise=True),
        'charge1': dict(kind='qnep1'),
        'charge2': dict(kind='qnep2'),
        'dipole': dict(kind='nep_dipole'),
        'polarizability': dict(kind='nep_polarizability'),
        'zbl_fixed': dict(zbl='zbl 1 3.5'),
        'zbl_typewise': dict(zbl='zbl 2 4 0.65', typewise=True),
        'zbl_flexible': dict(zbl='zbl 0 0'),
        'zbl_charge1': dict(kind='qnep1', zbl='zbl 1 3.5'),
        'zbl_charge2': dict(kind='qnep2', zbl='zbl 1 3.5'),
    }
    models = {}
    for name, options in settings.items():
        path = directory / (name + '.txt')
        path.write_text(model_text(**options))
        models[name] = path
    return models


def angular_cases():
    """Cover every angular order and the shared-kernel callers without a full product."""
    cases = {}
    for l_max in range(2, 9):
        # q_123/q_233 need l=3; q_134 needs l=4.
        flags = (1, 1, 1, int(l_max >= 3), int(l_max >= 3), int(l_max >= 4))
        cases['nep_l{}'.format(l_max)] = dict(l_max=l_max, flags=flags)
        if l_max in (2, 5, 8):
            cases['typewise_l{}'.format(l_max)] = dict(l_max=l_max, flags=flags, typewise=True)
            for kind in ('qnep1', 'qnep2', 'qnep3', 'nep_dipole', 'nep_polarizability'):
                cases['{}_l{}'.format(kind, l_max)] = dict(kind=kind, l_max=l_max, flags=flags)
    cases['zbl_fixed_l5'] = dict(l_max=5, zbl='zbl 1 3.5')
    cases['zbl_flexible_l8'] = dict(l_max=8, typewise=True, zbl='zbl 0 0')
    return cases


