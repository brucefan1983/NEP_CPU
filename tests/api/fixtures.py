def angular_descriptor_oracle(model, frame):
    """Three-body descriptors from the addition theorem and Legendre recurrence.

    This uses pair angles directly, with no Cartesian harmonic coefficients.
    Frames must be nonperiodic clusters inside a sufficiently large box.
    """
    fields = {row[0]: row[1:] for row in map(str.split, model.read_text().splitlines()) if row}
    types = int(fields['nep'][0])
    nr, na = map(int, fields['n_max'])
    br, ba = map(int, fields['basis_size'])
    l_max = int(fields['l_max'][0])
    cutoffs = list(map(float, fields['cutoff'][:-2]))
    if len(cutoffs) == 2:
        cutoffs *= types
    count = types * types * ((nr + 1) * (br + 1) + (na + 1) * (ba + 1))
    coefficients = read_block(model, 'parameters')[-count:]
    offset = types * types * (nr + 1) * (br + 1)
    scalers = read_block(model, 'q_scaler')[nr + 1:]
    result = []
    for i, (t1, r1) in enumerate(zip(frame['type'], frame['position'])):
        neighbors = []
        for j, (t2, r2) in enumerate(zip(frame['type'], frame['position'])):
            if i == j:
                continue
            r = [b - a for a, b in zip(r1, r2)]
            distance = math.sqrt(sum(x * x for x in r))
            cutoff = (cutoffs[2 * t1 + 1] + cutoffs[2 * t2 + 1]) / 2
            if distance >= cutoff:
                continue
            angle = math.acos(2 * (distance / cutoff - 1) ** 2 - 1)
            fc = (1 + math.cos(math.pi * distance / cutoff)) / 2
            basis = [(1 + math.cos(k * angle)) * fc / 2 for k in range(ba + 1)]
            start = offset + (t1 * types + t2) * (na + 1) * (ba + 1)
            g = [sum(coefficients[start + n * (ba + 1) + k] * basis[k] for k in range(ba + 1))
                 for n in range(na + 1)]
            neighbors.append(([x / distance for x in r], g))
        q = [0.] * (l_max * (na + 1))
        for u, g1 in neighbors:
            for v, g2 in neighbors:
                cosine = max(-1., min(1., sum(x * y for x, y in zip(u, v))))
                previous, current = 1., cosine
                for l in range(1, l_max + 1):
                    for n in range(na + 1):
                        q[(l - 1) * (na + 1) + n] += (2 * l + 1) / (4 * math.pi) * g1[n] * g2[n] * current
                    previous, current = current, ((2 * l + 1) * cosine * current - l * previous) / (l + 1)
        result.append([value * scale for value, scale in zip(q, scalers)])
    return result


def raw_charges(model, descriptors, types):
    """Forward-only ANN oracle for synthetic charge fixtures (no force kernels).

    find_descriptor returns scaled descriptors. The charge mean is removed by
    compute; the raw values are needed for the GPUMD bond-based BEC definition.
    """
    import math
    dim = len(descriptors[0])
    neurons = next(int(line.split()[1]) for line in model.read_text().splitlines()
                   if line.startswith('ann '))
    values = read_block(model, 'parameters')
    width = neurons * (dim + 3)
    result = []
    for t, q in zip(types, descriptors):
        start = t * width
        hidden = [math.tanh(sum(values[start + j * dim + d] * q[d] for d in range(dim))
                            - values[start + neurons * dim + j]) for j in range(neurons)]
        result.append(sum(values[start + neurons * (dim + 2) + j] * hidden[j]
                          for j in range(neurons)))
    return result


def read_block(model, name):
    """Read a numerical block from the canonical test fixtures."""
    lines = model.read_text().splitlines()
    start = next(i for i, line in enumerate(lines) if line.startswith('@ ' + name + ' '))
    count = int(lines[start].split()[2])
    tokens = []
    for line in lines[start + 1:]:
        tokens.extend(line.split())
        if len(tokens) >= count:
            return list(map(float, tokens[:count]))
    raise ValueError('Truncated fixture block: ' + name)


def asymmetric_model(kind, n_max, basis_size):
    """Three species with distinct ordered-pair coefficients and unequal segment sizes."""
    dim, neurons, types = n_max[0] + 1 + (n_max[1] + 1) * 10, 5, 3
    charge = kind.startswith('qnep')
    ann_count = types * neurons * (dim + 2 + charge) + 1 + charge
    if kind == 'nep_polarizability':
        ann_count *= 2
    rng = random.Random(987)
    parameters = [rng.uniform(-0.25, 0.25) for _ in range(ann_count)]
    if charge:
        parameters[-2] = 1.7
    coefficients = []
    for n_max_one, basis_one in zip(n_max, basis_size):
        segment = [[[[rng.uniform(-0.25, 0.25) for _ in range(basis_one + 1)]
                     for _ in range(n_max_one + 1)] for _ in range(types)] for _ in range(types)]
        coefficients.append(segment)
        parameters += [c for center in segment for neighbor in center for row in neighbor for c in row]
    lines = ['nep 3 C Si O', 'format_version 1', 'model ' + kind, 'cutoff 5 4 100 100',
             'n_max {} {}'.format(*n_max), 'basis_size {} {}'.format(*basis_size),
             'l_max 4 2 1 1 1 1 1', 'ann 5 0']
    if kind not in ('nep_dipole', 'nep_polarizability'):
        lines += ['energy_reference 0 0 0']
    lines += ['@ parameters ' + str(len(parameters))]
    lines += [format(v, '.17g') for v in parameters]
    lines += ['@ q_scaler ' + str(dim)]
    lines += [format(0.7 + 0.03 * d, '.17g') for d in range(dim)]
    return '\n'.join(lines) + '\n', coefficients
